`timescale 1ns/1ps
`default_nettype none

// DS1 depthwise-only streaming endpoint.  This is deliberately an isolated
// candidate: it is not instantiated by cnn_top or by the retained runner.
//
// The feature memory interface returns one complete 16-channel pixel (128
// bits, little-endian bytes).  A request is held until mem_req_ready and is
// followed by exactly one response; the response may be delayed arbitrarily.
// This makes a one-cycle synchronous bank and a delayed bank equivalent at
// the transaction boundary while keeping the address/response bookkeeping
// explicit.  The endpoint first fills its private feature store, then emits
// one 16-channel DW-requantized vector for each of the 1024 DS1 pixels.
//
// cfg_data is the packed DS1 configuration stream generated by
// python/ds12_stream_reference.py.  Words 0..35 are 4x INT8 DW weights,
// 36..51 are bias, 52..67 multiplier, and 68..83 post-multiply shift.
// DW output zero point and activation are the C0 DS1 contract (0, 0..127).
// Four rotating context slots are reserved and checked.  Context n covers
// eight pixels, owner=n[0], epoch=n/2, and context=n[1:0].
module ds12_stream_ds1_dw_endpoint #(
    parameter integer IMAGE_H = 32,
    parameter integer IMAGE_W = 32,
    parameter integer CHANNELS = 16,
    parameter integer CONTEXT_PIXELS = 8,
    parameter integer CONTEXTS = 4,
    parameter integer INPUT_BASE = 0
) (
    input  wire                         clk,
    input  wire                         rst_n,
    input  wire                         start,
    output wire                         ready,
    input  wire                         cfg_valid,
    output wire                         cfg_ready,
    input  wire [31:0]                  cfg_data,
    input  wire                         cfg_last,

    output wire                         mem_req_valid,
    input  wire                         mem_req_ready,
    output wire                         mem_req_write,
    output wire [31:0]                  mem_req_addr,
    output wire [127:0]                 mem_req_wdata,
    output wire [15:0]                  mem_req_strb,
    output wire [1:0]                   mem_req_context,
    output wire                         mem_req_owner,
    output wire [31:0]                  mem_req_epoch,
    input  wire                         mem_resp_valid,
    input  wire [127:0]                 mem_resp_rdata,

    output wire                         dw_valid,
    input  wire                         dw_ready,
    output wire [127:0]                 dw_data,
    output wire [5:0]                   dw_row,
    output wire [9:0]                   dw_pixel,
    output wire [1:0]                   dw_context,
    output wire                         dw_owner,
    output wire [31:0]                  dw_epoch,
    output wire                         dw_last,

    output wire                         done,
    output wire                         error,
    output wire [31:0]                  input_read_count,
    output wire [31:0]                  padding_tap_count,
    output wire [31:0]                  dw_mac_count,
    output wire [3:0]                   context_peak
);
    localparam integer PIXELS = IMAGE_H * IMAGE_W;
    localparam integer CFG_WORDS = 84;
    localparam integer RQ_GROUPS = 4;

    localparam [3:0] ST_CFG = 4'd0;
    localparam [3:0] ST_LOAD_REQ = 4'd1;
    localparam [3:0] ST_LOAD_WAIT = 4'd2;
    localparam [3:0] ST_CALC = 4'd3;
    localparam [3:0] ST_RQ = 4'd4;
    localparam [3:0] ST_OUT = 4'd5;
    localparam [3:0] ST_DONE = 4'd6;

    reg [3:0] state;
    reg [6:0] cfg_index;
    reg [10:0] load_pixel;
    reg [10:0] out_pixel;
    reg [2:0] rq_group;
    reg [1:0] rq_context;
    reg [31:0] rq_epoch;
    reg rq_owner;
    reg [127:0] dw_data_r;
    reg dw_valid_r;
    reg done_r;
    reg error_r;

    reg signed [7:0] dw_weight [0:15][0:8];
    reg signed [31:0] dw_bias [0:15];
    reg signed [31:0] dw_multiplier [0:15];
    reg [5:0] dw_shift [0:15];
    reg signed [7:0] feature [0:PIXELS-1][0:15];
    reg signed [31:0] accum [0:15];

    reg context_in_use [0:CONTEXTS-1];
    reg context_owner [0:CONTEXTS-1];
    reg [31:0] context_epoch [0:CONTEXTS-1];

    reg [31:0] input_read_count_r;
    reg [31:0] padding_tap_count_r;
    reg [31:0] dw_mac_count_r;
    reg [3:0] context_peak_r;

    integer i;
    integer j;
    integer k;
    integer iy;
    integer ix;
    integer tap;
    integer chan;
    integer slot;
    integer ordinal;
    integer pad_count_tmp;
    reg signed [7:0] tap_value;
    reg signed [31:0] tap_sum;

    function automatic signed [7:0] requant_dw;
        input signed [31:0] acc_value;
        input signed [31:0] bias_value;
        input signed [31:0] multiplier_value;
        input [5:0] shift_value;
        reg signed [31:0] biased;
        reg signed [63:0] product;
        reg signed [64:0] abs_product;
        reg signed [64:0] rounded;
        reg signed [64:0] shifted;
        reg signed [64:0] value;
        begin
            biased = acc_value + bias_value;
            product = biased * multiplier_value;
            if (product < 0) begin
                abs_product = -$signed({product[63], product});
                rounded = -((abs_product + 65'sd1073741824) >>> 31);
            end else begin
                rounded = ($signed({product[63], product}) + 65'sd1073741824) >>> 31;
            end
            shifted = rounded >>> shift_value;
            value = shifted;
            if (value > 65'sd127)
                value = 65'sd127;
            else if (value < -65'sd128)
                value = -65'sd128;
            // C0 DS1 DW activation: ReLU6-like exported range 0..127.
            if (value < 0)
                value = 0;
            else if (value > 127)
                value = 127;
            requant_dw = value[7:0];
        end
    endfunction

    assign ready = (state == ST_CFG) && (cfg_index >= CFG_WORDS);
    assign cfg_ready = (state == ST_CFG) && (cfg_index < CFG_WORDS);
    assign mem_req_valid = (state == ST_LOAD_REQ);
    assign mem_req_write = 1'b0;
    assign mem_req_addr = INPUT_BASE + (load_pixel * 32'd16);
    assign mem_req_wdata = 128'd0;
    assign mem_req_strb = 16'd0;
    assign mem_req_context = ((load_pixel / CONTEXT_PIXELS) & 2'd3);
    assign mem_req_owner = ((load_pixel / CONTEXT_PIXELS) & 1'd1);
    assign mem_req_epoch = ((load_pixel / CONTEXT_PIXELS) >> 1);
    assign dw_valid = dw_valid_r;
    assign dw_data = dw_data_r;
    assign dw_row = out_pixel / IMAGE_W;
    assign dw_pixel = out_pixel;
    assign dw_context = rq_context;
    assign dw_owner = rq_owner;
    assign dw_epoch = rq_epoch;
    assign dw_last = dw_valid_r && (out_pixel == PIXELS-1);
    assign done = done_r;
    assign error = error_r;
    assign input_read_count = input_read_count_r;
    assign padding_tap_count = padding_tap_count_r;
    assign dw_mac_count = dw_mac_count_r;
    assign context_peak = context_peak_r;

    always @(posedge clk) begin
        if (!rst_n) begin
            state <= ST_CFG;
            cfg_index <= 0;
            load_pixel <= 0;
            out_pixel <= 0;
            rq_group <= 0;
            rq_context <= 0;
            rq_owner <= 0;
            rq_epoch <= 0;
            dw_data_r <= 0;
            dw_valid_r <= 1'b0;
            done_r <= 1'b0;
            error_r <= 1'b0;
            input_read_count_r <= 0;
            padding_tap_count_r <= 0;
            dw_mac_count_r <= 0;
            context_peak_r <= 0;
            for (i = 0; i < CHANNELS; i = i + 1) begin
                dw_bias[i] <= 0;
                dw_multiplier[i] <= 0;
                dw_shift[i] <= 0;
                accum[i] <= 0;
                for (j = 0; j < 9; j = j + 1)
                    dw_weight[i][j] <= 0;
            end
            // feature[] is completely overwritten by the preload phase; it
            // is intentionally not reset (large unpacked memories are not a
            // portable reset target for FPGA inference).
            for (i = 0; i < CONTEXTS; i = i + 1) begin
                context_in_use[i] <= 1'b0;
                context_owner[i] <= 1'b0;
                context_epoch[i] <= 0;
            end
        end else begin
            case (state)
                ST_CFG: begin
                    if (cfg_valid && cfg_ready) begin
                        if (cfg_index < 36) begin
                            for (j = 0; j < 4; j = j + 1)
                                if ((cfg_index * 4 + j) < 144)
                                    dw_weight[(cfg_index * 4 + j) / 9][(cfg_index * 4 + j) % 9] <= $signed(cfg_data[(j*8) +: 8]);
                        end else if (cfg_index < 52) begin
                            dw_bias[cfg_index - 36] <= $signed(cfg_data);
                        end else if (cfg_index < 68) begin
                            dw_multiplier[cfg_index - 52] <= $signed(cfg_data);
                        end else if (cfg_index < 84) begin
                            dw_shift[cfg_index - 68] <= cfg_data[5:0];
                        end
                        cfg_index <= cfg_index + 1'b1;
                    end
                    if (start && (cfg_index >= CFG_WORDS)) begin
                        state <= ST_LOAD_REQ;
                        load_pixel <= 0;
                        out_pixel <= 0;
                        input_read_count_r <= 0;
                        padding_tap_count_r <= 0;
                        dw_mac_count_r <= 0;
                        done_r <= 1'b0;
                        error_r <= 1'b0;
                        for (i = 0; i < CONTEXTS; i = i + 1) begin
                            context_in_use[i] <= (i < CONTEXTS);
                            context_owner[i] <= i[0];
                            context_epoch[i] <= i / 2;
                        end
                        context_peak_r <= CONTEXTS[3:0];
                    end
                end

                ST_LOAD_REQ: begin
                    if (mem_req_ready)
                        state <= ST_LOAD_WAIT;
                end

                ST_LOAD_WAIT: begin
                    if (mem_resp_valid) begin
                        for (j = 0; j < CHANNELS; j = j + 1)
                            feature[load_pixel][j] <= $signed(mem_resp_rdata[(j*8) +: 8]);
                        input_read_count_r <= input_read_count_r + 1'b1;
                        if (load_pixel == PIXELS-1) begin
                            out_pixel <= 0;
                            state <= ST_CALC;
                        end else begin
                            load_pixel <= load_pixel + 1'b1;
                            state <= ST_LOAD_REQ;
                        end
                    end
                end

                ST_CALC: begin
                    // One 3x3 MAC per lane.  SAME padding is the input zero
                    // point (zero for the real DS1 export).
                    ordinal = out_pixel / CONTEXT_PIXELS;
                    slot = ordinal % CONTEXTS;
                    rq_context <= ordinal & 3;
                    rq_owner <= ordinal & 1;
                    rq_epoch <= ordinal / 2;
                    if (!context_in_use[slot] || context_owner[slot] != (ordinal & 1) || context_epoch[slot] != (ordinal / 2))
                        error_r <= 1'b1;
                    pad_count_tmp = 0;
                    for (chan = 0; chan < CHANNELS; chan = chan + 1) begin
                        tap_sum = 0;
                        for (tap = 0; tap < 9; tap = tap + 1) begin
                            iy = (out_pixel / IMAGE_W) + (tap / 3) - 1;
                            ix = (out_pixel % IMAGE_W) + (tap % 3) - 1;
                            if ((iy < 0) || (iy >= IMAGE_H) || (ix < 0) || (ix >= IMAGE_W)) begin
                                tap_value = 0;
                                // Count spatial padding positions, not one
                                // event per channel lane.
                                if (chan == 0)
                                    pad_count_tmp = pad_count_tmp + 1;
                            end else begin
                                tap_value = feature[iy * IMAGE_W + ix][chan];
                            end
                            tap_sum = tap_sum + tap_value * dw_weight[chan][tap];
                        end
                        accum[chan] <= tap_sum;
                    end
                    padding_tap_count_r <= padding_tap_count_r + pad_count_tmp;
                    dw_mac_count_r <= dw_mac_count_r + (CHANNELS * 9);
                    rq_group <= 0;
                    state <= ST_RQ;
                end

                ST_RQ: begin
                    for (chan = 0; chan < 4; chan = chan + 1)
                        dw_data_r[((rq_group * 4 + chan) * 8) +: 8] <= requant_dw(
                            accum[rq_group * 4 + chan], dw_bias[rq_group * 4 + chan],
                            dw_multiplier[rq_group * 4 + chan], dw_shift[rq_group * 4 + chan]);
                    if (rq_group == RQ_GROUPS-1) begin
                        dw_valid_r <= 1'b1;
                        state <= ST_OUT;
                    end else begin
                        rq_group <= rq_group + 1'b1;
                    end
                end

                ST_OUT: begin
                    if (dw_valid_r && dw_ready) begin
                        dw_valid_r <= 1'b0;
                        if (out_pixel == PIXELS-1) begin
                            done_r <= 1'b1;
                            state <= ST_DONE;
                        end else begin
                            // Release the completed context slot only after
                            // its eighth accepted vector, then rotate it to
                            // the next epoch.  This is the bank/epoch fence.
                            if (((out_pixel + 1) % CONTEXT_PIXELS) == 0) begin
                                ordinal = (out_pixel / CONTEXT_PIXELS);
                                slot = ordinal % CONTEXTS;
                                context_in_use[slot] <= 1'b0;
                                if ((ordinal + CONTEXTS) < (PIXELS / CONTEXT_PIXELS)) begin
                                    context_in_use[slot] <= 1'b1;
                                    context_owner[slot] <= (ordinal + CONTEXTS) & 1;
                                    context_epoch[slot] <= (ordinal + CONTEXTS) / 2;
                                end
                            end
                            out_pixel <= out_pixel + 1'b1;
                            state <= ST_CALC;
                        end
                    end
                end

                ST_DONE: begin
                    state <= ST_DONE;
                end
                default: state <= ST_CFG;
            endcase
        end
    end
endmodule

`default_nettype wire
